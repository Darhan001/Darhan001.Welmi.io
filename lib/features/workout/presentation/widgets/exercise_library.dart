/// Определяет группу мышц по ключевым словам (порядок важен:
/// «бицепс бедра» — это мышца ноги, а не руки).
String? _muscleGroup(String muscle) {
  final m = muscle.toLowerCase();
  if (m.contains('груд')) return 'груд';
  if (m.contains('спин') || m.contains('широчай')) return 'спин';
  if (m.contains('ягод')) return 'ягод';
  if (m.contains('бедр')) return 'бедр';
  if (m.contains('икр') || m.contains('голен')) return 'икр';
  if (m.contains('ног')) return 'ног';
  if (m.contains('плеч') || m.contains('дельт')) return 'плеч';
  if (m.contains('трицеп')) return 'трицеп';
  if (m.contains('бицеп')) return 'бицеп';
  if (m.contains('пресс') || m.contains('кор') || m.contains('живот')) return 'пресс';
  return null;
}

