/// Список альтернативных упражнений для группы мышц,
/// с учётом инвентаря пользователя ([equipment] — как в плане).
List<String> alternativesFor(String muscle, {String equipment = ''}) {
  final group = _muscleGroup(muscle);
  final eq = equipment.toLowerCase();

  Map<String, List<String>> pool = _alternatives;
  if (eq.contains('собственный вес') ||
      eq.contains('без инвентаря') ||
      eq.contains('вес тела')) {
    pool = _alternativesBodyweight;
  } else if (eq.contains('турник') || eq.contains('резин')) {
    pool = _alternativesCalisthenics;
  } else if (eq.contains('зал') ||
      eq.contains('тренажёр') ||
      eq.contains('штанга')) {
    pool = _alternativesGym;
  }

  final list = group != null ? pool[group] : null;
  if (list == null || list.isEmpty) {
    return ['Отжимания от пола', 'Приседания', 'Планка'];
  }
  return list;
}

/// Шаги техники выполнения для упражнения (если у модели их нет).
