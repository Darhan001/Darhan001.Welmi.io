/// Рецепты, сгруппированные по категориям для горизонтальных чипов.
List<Recipe> buildSeedRecipes() =>
    List.unmodifiable(_catalog.map(_toRecipe));

Recipe _toRecipe(_SeedRecipe seed) {
  final minutes = seed.minutes;
  final tags = <String>{
    seed.category.toLowerCase(),
    if (seed.vegetarian) 'вегетарианское',
    if (seed.protein >= 30) 'высокобелковое',
    if (seed.calories <= 300) 'низкокалорийное',
    if (minutes <= 25) 'быстрое',
    seed.slug,
    ...seed.ingredients.map((e) => e.$1.toLowerCase()),
  }.toList();

  return Recipe(
    id: seed.mealDbId == null ? 'welmi-${seed.slug}' : 'mealdb-${seed.mealDbId}',
    mealDbId: seed.mealDbId,
    title: seed.title,
    description: seed.description,
    imageUrl: seed.imageUrl,
    imagePath: 'assets/images/recipes/${seed.photoFile}',
    imageCredit: seed.imageCredit,
    category: seed.category,
    calories: seed.calories,
    proteinGrams: seed.protein,
    fatGrams: seed.fat,
    carbsGrams: seed.carbs,
    fiberGrams: seed.fiber,
    sugarGrams: seed.sugar,
    sodiumMg: seed.sodium,
    cookingTimeMinutes: minutes,
    servings: 1,
    servingWeightGrams: seed.weightGrams,
    nutritionIsEstimate: true,
    tags: tags,
    ingredients: seed.ingredients
        .map(
          (e) => RecipeIngredient(
            name: e.$1,
            amount: e.$2,
            // Покомпонентная калорийность не публикуется источником — не выдумываем.
            calories: 0,
          ),
        )
        .toList(),
    steps: [
      for (var i = 0; i < seed.steps.length; i++)
        RecipeStep(stepNumber: i + 1, description: seed.steps[i]),
    ],
    isVegetarian: seed.vegetarian,
    isHighProtein: seed.protein >= 30,
    isLowCalorie: seed.calories <= 300,
    isQuick: minutes <= 25,
  );
}

