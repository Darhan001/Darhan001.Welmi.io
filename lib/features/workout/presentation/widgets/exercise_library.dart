  final group = _muscleGroup(muscle);
  switch (group) {
    case 'груд':
      return [
        'Встань в исходное положение, спина прямая, пресс напряжён.',
        'Выполни «$exerciseName» плавно, с полной амплитудой, без рывков.',
        'На усилии делай выдох, на расслаблении — вдох.',
      ];
    case 'спин':
      return [
        'Держи спину ровной, лопатки сведи перед началом движения.',
        'Тяни вес мышцами спины, а не руками, локти вдоль корпуса.',
        'Плавно возвращайся в исходное положение, не «бросая» вес.',
      ];
    case 'ног':
    case 'ягод':
    case 'бедр':
    case 'икр':
      return [
        'Встань устойчиво, ноги на ширине плеч, пятки прижаты к полу.',
        'Выполняй движение за счёт ног и ягодиц, колени не «гуляют» внутрь.',
        'Контролируй каждое повторение — без раскачки корпуса.',
      ];
    case 'плеч':
      return [
        'Сядь или встань ровно, пресс напряжён, поясница не прогибается.',
        'Поднимай гантели плавно, локти слегка согнуты.',
        'В верхней точке не стучи гантелями — опускай медленно.',
      ];
    case 'трицеп':
      return [
        'Локти держи неподвижно прижатыми к корпусу на протяжении всего подхода.',
        'Разгибай руки полностью, но без блокировки локтя.',
        'Движение медленное и контролируемое в обе стороны.',
      ];
    case 'бицеп':
      return [
        'Локти прижаты к корпусу, корпус неподвижен.',
        'Сгибай руки плавно, не помогая раскачкой.',
        'Опускай гантели медленно, полностью разгибая локти.',
      ];
    case 'пресс':
      return [
        'Дыши ровно, не задерживай дыхание.',
        'Работай мышцами живота, а не инерцией.',
        'Удерживай корпус в напряжении на протяжении всего подхода.',
      ];
    default:
      return [
        'Прими устойчивое исходное положение, спина прямая.',
        'Выполняй движение плавно и с полной амплитудой.',
        'Следи за дыханием: выдох на усилии, вдох на расслаблении.',
      ];
  }
}

/// Описание упражнения по умолчанию.
String descriptionFor(String muscle, String equipment) {
  return 'Упражнение на группу «$muscle» с оборудованием «$equipment». '
      'Выполняй плавно, с полной амплитудой и под контролем.';
}

/// Создаёт альтернативное упражнение на основе текущего (для «Заменить»).
WorkoutExercise alternativeExercise(WorkoutExercise base, String name) {
  return WorkoutExercise(
    name: name,
    muscle: base.muscle,
    equipment: base.equipment,
    sets: base.sets,
    reps: base.reps,
    rest: base.rest,
    difficulty: base.difficulty,
    calories: base.calories,
    description: descriptionFor(base.muscle, base.equipment),
    technique: techniqueFor(name, base.muscle),
    tips: 'Следи за техникой: одно качественное повторение лучше десяти «наспех».',
  );
}
